"""``python -m devkit re ghidra-sync``: AzurKit's knowledge pushed into a
live Ghidra project (Modkit's, ported in Step 4.11d2).

Takes every named VA AzurKit tracks (the RE data's anchors,
``devkit/re/data/anchors.toml``; the facts' functions,
``src/azurkit/core/facts.usa.json``; the packs' sites) and writes them
back into the currently-open Ghidra project as renamed functions + plate
comments — so the next time a human opens those addresses in Ghidra they
see AzurKit's understanding instead of ``FUN_00085700`` and a blank
annotation pane.

## Design

Reads the knowledge by importing it (the harvesters below).  Builds a
list of
:class:`SyncAction` records describing what SHOULD change on
the Ghidra side; optionally applies them via
:class:`GhidraClient`.

Three action kinds:

- ``rename`` — function's current name differs from ours, which
  comes from AzurKit's record.
- ``comment`` — we have a docstring-quality annotation that
  belongs as a plate comment on the function.
- ``keep`` — the Ghidra name + comment are already set the way
  we want them; no-op.

## Safety

Dry-run mode is the default.  Applying requires ``apply=True``
explicitly, and a client whose ``target`` names the program served
(:meth:`GhidraClient.check_target`; ``--target``).  The apply path
renames only a function whose name Ghidra made up itself (``FUN_*``,
``thunk_FUN_*``, ``caseD_*``, …: ``ghidra_snapshot.is_auto_name``, the
filter ``ghidra-snapshot`` uses), and replaces only a plate comment
that is empty or carries :data:`SYNC_MARKER` (AZ-194, Q204); it keeps
a name a user chose (``gravity_integrate`` → ``gravity_integrate_raw``)
and a hand-written plate comment unless the user passes ``--force``.

## API

:func:`plan_sync(client)` → list of :class:`SyncAction` records.
:func:`apply_sync(client, actions, *, force=False)` → mutates
Ghidra state.  Returns a summary dict with counts + any errors.
:func:`emit_plan(client, actions)` → the same renames, and the
functions :data:`CREATE_FUNCTIONS` lists, as ``ghidra-apply`` plan
lines (``--emit-plan FILE``; Step X.47).
"""

