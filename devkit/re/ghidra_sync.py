# Mapping from header-side C types to Ghidra's DTM type names.
# Ghidra uses lowercased builtins for primitive widths; pointers
# collapse to the ``void *`` typedef.  Anything unknown falls back
# to a typed ``undefined`` of the field's intrinsic width.
_C_TYPE_TO_GHIDRA = {
    # Signed-int typedef spellings we accept (both `i32`-style +
    # `s32`-style since the header uses `i` but some legacy notes
    # quote `s`):
    "u8":       "uchar",    "i8":       "char",    "s8":       "char",
    "u16":      "ushort",   "i16":      "short",   "s16":      "short",
    "u32":      "uint",     "i32":      "int",     "s32":      "int",
    "u64":      "ulonglong",
    "i64":      "longlong", "s64":      "longlong",
    "f32":      "float",    "f64":      "double",
    "float":    "float",    "double":   "double",
    "char":     "char",     "uchar":    "uchar",
    "byte":     "byte",     "bool":     "bool",
    "int":      "int",      "uint":     "uint",
    "long":     "long",     "ulong":    "ulong",
    "short":    "short",    "ushort":   "ushort",
    "void":     "void",
}


def _ghidra_type_for(c_type: str) -> str:
    """Map a header C type to Ghidra's DTM spelling; an array keeps its
    dimensions (``u8[12]`` -> ``uchar[12]``, AZ-200)."""
    t, bracket, dims = c_type.strip().replace("const ", "").replace(
        "volatile ", "").partition("[")
    elem = ("void *" if "*" in t
            else _C_TYPE_TO_GHIDRA.get(t.split()[-1], "undefined4"))
    return elem + bracket + dims


def plan_struct_sync(client: GhidraClient, *,
                     header: Path | None = None,
                     recreate_existing: bool = False,
                     ) -> list[StructAction]:
    """Plan struct pushes from ``header`` (default the RE data's
    ``structs.h``) into Ghidra's DTM.

    For each ``typedef struct`` block in the header:

    - If Ghidra doesn't have a struct with that name, plan
      ``kind="create"`` with all fields.
    - If Ghidra already has one AND ``recreate_existing`` is
      ``False`` (default), plan ``kind="keep"`` — leaves whatever
      Ghidra has alone.
    - If ``recreate_existing=True``, plan ``kind="recreate"``;
      apply_struct_sync will DELETE + re-create.

    Skips fields with offset -1 (our header parser's "no comment
    giving the offset" sentinel) since Ghidra needs a concrete
    offset for each member.  Raises :class:`GhidraClientError` on any
    lookup error but stock's ``STRUCT_NOT_FOUND`` (AZ-202).
    """
    structs = parse_header_structs(header or HEADER)
    actions: list[StructAction] = []
    for hs in structs:
        has_fields = sum(1 for f in hs.fields if f.offset >= 0)
        size = hs.declared_size or hs.inferred_size() or 0
        try:
            existing = client.get_struct(hs.name)
        except GhidraClientError as exc:
            if not exc.means_absent("STRUCT_NOT_FOUND"):
                raise
            existing = None

        if existing is None:
            actions.append(StructAction(
                name=hs.name, size=size, field_count=has_fields,
                kind="create",
                rationale=(f"new: {has_fields} fields, size={size}")))
        elif recreate_existing:
            actions.append(StructAction(
                name=hs.name, size=size, field_count=has_fields,
                kind="recreate",
                rationale=(f"recreating: Ghidra has "
                           f"{len(existing.fields)} fields, "
                           f"header has {has_fields}")))
        else:
            actions.append(StructAction(
                name=hs.name, size=size, field_count=has_fields,
                kind="keep",
                rationale=(f"Ghidra already has {hs.name!r}; pass "
                           f"--recreate-structs to overwrite")))
    return actions


def apply_struct_sync(client: GhidraClient,
                      actions: Iterable[StructAction],
                      *,
                      header: Path | None = None,
                      report: SyncReport | None = None,
                      ) -> SyncReport:
    """Execute a struct-sync plan against ``client``.

    For each ``create`` / ``recreate`` action: creates the struct at
    the header's size, then puts every field from the header over the
    bytes at its offset, so the size stays (skipping offset=-1
    fields, which have no committed layout in the header).

    ``recreate`` actions DELETE the existing struct first — this
    wipes any Ghidra variables typed with the old layout.  Use
    cautiously.
    """
    header_structs = {s.name: s for s in parse_header_structs(header or HEADER)}
    report = report or SyncReport()

    for act in actions:
        if act.kind == "keep":
            report.structs_skipped += 1
            continue

        hs = header_structs.get(act.name)
        if hs is None:
            report.errors.append(
                f"struct {act.name}: no matching definition in "
                f"header — skipping")
            continue

        try:
            if act.kind == "recreate":
                try:
                    client.delete_struct(act.name)
                except GhidraClientError as exc:
                    # Not-found on delete means someone removed it
                    # between plan + apply; keep going.
                    if "not found" not in str(exc).lower():
                        raise
            client.create_struct(
                act.name,
                size=act.size or 1,
                description=f"Mirror of {hs.name} from structs.h")
            report.structs_created += 1

            fields_with_offsets = [
                f for f in hs.fields if f.offset >= 0]
            # Sort by offset so fields land in the right order
            fields_with_offsets.sort(key=lambda f: f.offset)
            for hf in fields_with_offsets:
                try:
                    client.add_struct_field(
                        act.name,
                        field_name=hf.name,
                        field_type=_ghidra_type_for(hf.c_type),
                        offset=hf.offset,
                        comment=(hf.comment or "")[:200])
                    report.struct_fields_added += 1
                except GhidraClientError as exc:
                    report.errors.append(
                        f"struct {act.name}.{hf.name}: {exc}")

        except GhidraClientError as exc:
            report.errors.append(f"struct {act.name}: {exc}")

    return report


def format_struct_plan(actions: list[StructAction]) -> str:
    """Pretty-print a struct-sync plan (for dry-run output)."""
    if not actions:
        return "(no struct actions planned)"
    out: list[str] = []
    buckets: dict[str, list[StructAction]] = {
        "create": [], "recreate": [], "keep": []}
    for a in actions:
        buckets.setdefault(a.kind, []).append(a)
    for kind in ("create", "recreate", "keep"):
        grp = buckets.get(kind, [])
        out.append(f"=== struct {kind}  ({len(grp)}) ===")
        if not grp:
            out.append("  (none)")
            continue
        for a in grp:
            size_str = f"size={a.size}" if a.size else "size=?"
            out.append(
                f"  {a.name:30} {size_str:12} "
                f"fields={a.field_count:3d}  ({a.rationale})")
        out.append("")
    return "\n".join(out)


def format_plan(actions: list[SyncAction], *, force: bool = False) -> str:
    """Human-readable dry-run report.  It ends with what an apply with
    this ``force`` would do to the plate comments there now (AZ-194):
    counts, and each hand-written one it keeps or replaces, by its
    function's name or, where there is no function, its symbol."""
    if not actions:
        return "(no actions — all known symbols already reflect "\
               "Python-side state)"
    buckets: dict[str, list[SyncAction]] = {
        "rename": [], "comment": [], "keep": []}
    for a in actions:
        buckets.setdefault(a.kind, []).append(a)
    lines = []
    for kind in ("rename", "comment", "keep"):
        group = buckets.get(kind, [])
        lines.append(f"=== {kind}  ({len(group)}) ===")
        if not group:
            lines.append("  (none)")
            continue
        for a in group:
            if kind == "rename":
                lines.append(
                    f"  0x{a.va:08X}  "
                    f"{a.current_name!r} → {a.new_name!r}  "
                    f"({a.rationale})")
            elif kind == "comment":
                head = a.comment.splitlines()[0] if a.comment else ""
                lines.append(
                    f"  0x{a.va:08X}  "
                    f"{a.current_name!r}  annotate: {head}")
            else:
                lines.append(
                    f"  0x{a.va:08X}  {a.current_name!r}  "
                    f"{a.rationale}")
        lines.append("")
    plates = [a for a in actions if a.comment is not None
              and a.plate is not None and not _keeps_name(a, force)]
    hand = [a for a in plates if a.plate == "hand"]
    count = {state: sum(a.plate == state for a in plates)
             for state in ("empty", "sync")}
    if lines[-1]:
        lines.append("")
    lines += [f"=== plate comments  ({len(plates)}) ===",
              f"  {count['empty']:4d} empty: written",
              f"  {count['sync']:4d} the sync's own: refreshed",
              f"  {len(hand):4d} hand-written: "
              + ("replaced (--force)" if force
                 else "kept (--force replaces them)")]
    for a in hand:  # the function's name, else the symbol (its first line)
        name = (repr(a.current_name) if a.current_name
                else a.comment.splitlines()[0])
        lines.append(f"    0x{a.va:08X}  {name}")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    """The plan (a dry run) and, with ``--apply``, the writes. Exit 2 with
    nothing written when nothing answers on the port, the program isn't the
    USA XBE (AZ-326), or ``--apply``/``--target`` meets a program the target
    doesn't name (AZ-197); 1 when a read fails or an apply wrote with
    errors."""
    p = argparse.ArgumentParser(
        prog="python -m devkit re ghidra-sync",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        description=(
            "Every named VA AzurKit tracks (the facts' functions, the RE data's anchors, the packs' sites),\n"
            "written into the open Ghidra project as renamed functions and plate comments.\n\n"
            "A dry run by default. --apply writes, with --target naming the program to write (its\n"
            "programId, as GET /program serves it): exit 2 with nothing written unless the port serves\n"
            "that program. --apply keeps a name someone chose and a plate comment the sync didn't write;\n"
            "--force overwrites both. The symbol plan ends with what an apply would do to the plate\n"
            "comments there now; the struct plan (--push-structs) follows it. --emit-plan FILE writes\n"
            "Ghidra nothing: it writes the renames --apply would make (without --force) and the functions\n"
            "the sync's explicit list creates as a ghidra-apply plan, for the closed project."),
        epilog=(
            "Examples:\n"
            "  python -m devkit re ghidra-sync                # the dry run (port 8193)\n"
            "  python -m devkit re ghidra-sync --apply --target 'AzurikServe:/default.xbe' --port 8212\n"
            "  python -m devkit re ghidra-sync --port 8212 --emit-plan plan.json\n"
            "      # then: python -m devkit re ghidra-apply --plan plan.json --project P.gpr"))
    out = p.add_mutually_exclusive_group()
    out.add_argument("--apply", action="store_true", help="modify Ghidra (default: the dry run only)")
    out.add_argument("--emit-plan", metavar="FILE",
                     help="write the renames --apply makes without --force, and a create_function line for each "
                          "listed function no function starts at, as a ghidra-apply plan (writes Ghidra nothing)")
    p.add_argument("--target", metavar="PROJECT:/PROGRAM",
                   help="the programId --apply may write, e.g. 'AzurikServe:/default.xbe' (required with --apply; "
                        "exit 2 when the port serves another program)")
    p.add_argument("--force", action="store_true",
                   help="overwrite a name someone chose and a plate comment the sync didn't write (default: keep both)")
    p.add_argument("--push-structs", action="store_true",
                   help="also create the structs of devkit/re/data/structs.h Ghidra hasn't got")
    p.add_argument("--recreate-structs", action="store_true",
                   help="with --push-structs: DELETE and recreate the structs Ghidra has (wipes the types of "
                        "variables that used them)")
    p.add_argument("--port", type=int, default=None, help="Ghidra's port (default 8193)")
    p.add_argument("--json", action="store_true",
                   help="the plan as JSON (each symbol's plate: empty / sync / hand)")
    args = p.parse_args(argv)
    try:
        return _run(args)
    except Refused as exc:
        print(f"ghidra-sync: {exc}", file=sys.stderr)
        return exc.code


def _run(args: argparse.Namespace) -> int:
    client = connect(args.port, target=args.target)
    require_usa(client, "ghidra-sync")
    if args.apply or args.target is not None:
        try:  # before anything is planned or written (AZ-197, D35)
            client.check_target()
        except GhidraClientError as exc:
            raise Refused(f"{exc}; --apply writes only the program --target names. Nothing written.") from None
    try:
        actions = plan_sync(client)
        struct_actions = (plan_struct_sync(client, recreate_existing=args.recreate_structs)
                          if args.push_structs else [])
    except GhidraClientError as exc:
        raise Refused(str(exc), code=1) from None
    if args.json:
        emit({"symbols": [{"va": a.va, "kind": a.kind, "current_name": a.current_name,
                           "new_name": a.new_name, "comment": a.comment, "plate": a.plate,
                           "rationale": a.rationale} for a in actions],
              "structs": [{"name": s.name, "kind": s.kind, "size": s.size, "field_count": s.field_count,
                           "rationale": s.rationale} for s in struct_actions]}, as_json=True)
    else:
        print(format_plan(actions, force=args.force))
        if args.push_structs:
            print()
            print(format_struct_plan(struct_actions))
    if args.emit_plan:
        say = sys.stderr if args.json else sys.stdout
        try:
            lines = emit_plan(client, actions)
        except GhidraClientError as exc:
            raise Refused(str(exc), code=1) from None
        if not lines:
            print("\nghidra-sync: nothing to emit: every rename and create is in effect", file=say)
            return 0
        out = Path(args.emit_plan)
        write_plan(lines, out)
        creates = sum(line["op"] == "create_function" for line in lines)
        print(f"\nghidra-sync: wrote {len(lines)} ghidra-apply lines to {out}: {len(lines) - creates} renames, "
              f"{creates} creates\n  dry-run it: python -m devkit re ghidra-apply --plan {shlex.quote(str(out))} "
              "--project P.gpr", file=say)
    if not args.apply:
        return 0
    print(f"\nApplying symbol actions to {client.base_url}  (force={args.force})")
    report = apply_sync(client, actions, force=args.force)
    if struct_actions:
        print(f"Applying struct actions to {client.base_url}  (recreate={args.recreate_structs})")
        apply_struct_sync(client, struct_actions, report=report)
    print(f"  attempted:          {report.attempted}")
    print(f"  renamed:            {report.renamed}")
    print(f"  commented:          {report.commented}")
    print(f"  skipped (renames):  {report.skipped}")
    print(f"  kept (hand-written plate comments): {report.comments_kept}")
    if struct_actions:
        print(f"  structs_created:    {report.structs_created}")
        print(f"  struct_fields:      {report.struct_fields_added}")
        print(f"  structs_skipped:    {report.structs_skipped}")
    if report.errors:
        print(f"  errors     ({len(report.errors)}):")
        for err in report.errors[:20]:
            print(f"    - {err}")
        return 1
    return 0


