# Every plate comment the sync writes carries this line; it replaces
# only a comment that is empty or has it (AZ-194). Modkit's words, kept:
# the owner's project holds the comments Modkit's sync wrote, which this
# one refreshes rather than keeps as hand-written.
SYNC_MARKER = "Auto-generated by azurik-mod ghidra-sync."


def plate_state(text: str) -> str:
    """What ``--apply`` does to a plate comment (Q204): ``"empty"`` is
    written and ``"sync"`` (it carries :data:`SYNC_MARKER`) refreshed;
    ``"hand"`` (anything else) is kept unless ``force``."""
    return "empty" if not text else "sync" if SYNC_MARKER in text else "hand"


@dataclass(frozen=True)
class KnownSymbol:
    """One VA anchor / labelled function AzurKit knows."""

    va: int
    name: str
    kind: str  # "anchor" | "vanilla" | "patch_site"


def harvest_anchors() -> list[KnownSymbol]:
    """Every anchor of ``devkit/re/data/anchors.toml`` (its
    ``AZURIK_*_VA`` name and USA ``va``)."""
    from .xbe import anchors
    return [KnownSymbol(va=a["va"], name=name, kind="anchor") for name, a in anchors().items()]


def harvest_vanilla_symbols() -> list[KnownSymbol]:
    """Every function of the USA facts (``facts.usa.json``'s
    ``functions``: Modkit's vanilla-symbol registry)."""
    from azurkit.core import facts, gate
    return [KnownSymbol(va=f.va, name=f.name, kind="vanilla")
            for f in facts.of(gate.USA).functions.values()]


def harvest_patch_sites() -> list[KnownSymbol]:
    """Every USA patch-site VA across the packs, named
    ``<pack>:<site label>``: their sites and a ``custom_apply``'s places
    (its ``footprint``; Modkit listed those among its sites), as
    ``xbe.names_for`` names them."""
    from azurkit.tools import mods

    out: list[KnownSymbol] = []
    for pack in mods.PACKS.values():
        for site in (*pack.sites, *pack.footprint):
            va = getattr(site, "va", 0)
            if not va or not getattr(site, "on", lambda _region: True)("usa"):
                continue  # a virtual slider (va=0); another release's own site
            label_attr = getattr(site, "label", None)
            label = (f"{pack.name}:{label_attr}"
                     if label_attr else pack.name)
            out.append(KnownSymbol(va=va, name=label, kind="patch_site"))
    return out


@dataclass
class SyncAction:
    """One planned change to the Ghidra project.

    Attributes
    ----------
    va: int
        Target virtual address.
    kind: str
        ``rename`` / ``comment`` / ``keep``.
    current_name: str | None
        Ghidra's current function name at this VA (``None`` when
        the VA doesn't resolve to a function — common for data /
        BSS anchors that we still want to leave a comment on).
    new_name: str | None
        Name to PATCH to (``None`` on ``comment`` or ``keep``
        actions).
    comment: str | None
        Plate-comment text to POST (``None`` when not setting one).
    rationale: str
        One-line description used in the dry-run report.
    plate: str | None
        The plate comment there now, as :func:`plate_state` classes it
        (``None`` until :func:`plan_sync` has read it).
    """

    va: int
    kind: str
    current_name: str | None = None
    new_name: str | None = None
    comment: str | None = None
    rationale: str = ""
    plate: str | None = None


@dataclass
class SyncReport:
    """Result of an :func:`apply_sync` run."""

    attempted: int = 0
    renamed: int = 0
    commented: int = 0
    skipped: int = 0
    comments_kept: int = 0     # hand-written plate comments left alone
    structs_created: int = 0
    struct_fields_added: int = 0
    structs_skipped: int = 0
    errors: list[str] = field(default_factory=list)


@dataclass
class StructAction:
    """Planned Data-Type-Manager action for one struct."""

    name: str
    size: int | None           # inferred from declared_size / fields
    field_count: int
    kind: str                   # "create" | "keep" | "recreate"
    rationale: str = ""


