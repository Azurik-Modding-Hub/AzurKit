def emit_plan(client: GhidraClient, actions: list[SyncAction]) -> list[dict]:
    """``ghidra-sync --emit-plan``: the ``ghidra-apply`` lines
    (``ApplyPlan.java``) for the renames ``--apply`` makes without
    ``--force`` (a function whose name Ghidra made up itself), then a
    ``create_function`` line for each VA of :data:`CREATE_FUNCTIONS` that
    no function starts at, named when the registry names it."""
    lines = [{"op": "rename", "va": f"0x{a.va:X}", "from": a.current_name, "to": a.new_name}
             for a in actions if a.kind == "rename" and a.new_name and not _keeps_name(a, False)]
    starts = {f.address for f in client.iter_functions()}
    named = {s.va: s.name for s in harvest_vanilla_symbols()}
    lines += [{"op": "create_function", "va": f"0x{va:X}"} | ({"name": named[va]} if va in named else {})
              for va in CREATE_FUNCTIONS if va not in starts]
    return lines


def write_plan(lines: list[dict], path: Path) -> None:
    """A ``ghidra-apply`` plan file: the JSON list, one line per row."""
    path.write_text("[\n" + ",\n".join(json.dumps(line) for line in lines) + "\n]\n",
                    encoding="utf-8")


