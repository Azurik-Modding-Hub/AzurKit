def apply_sync(client: GhidraClient, actions: Iterable[SyncAction],
               *, force: bool = False) -> SyncReport:
    """Execute the plan against ``client``.

    Parameters
    ----------
    client: GhidraClient
    actions: iterable of :class:`SyncAction`
        Typically the output of :func:`plan_sync`.
    force: bool
        When ``True``, overwrite human-meaningful names and any plate
        comment.  Default ``False`` — rename only a name Ghidra made up
        itself (:func:`is_auto_name`), and replace only a plate comment
        that is empty or carries :data:`SYNC_MARKER` (a kept one counts
        in ``comments_kept``).

    Returns a :class:`SyncReport` with counts + any errors.
    """
    report = SyncReport()
    for action in actions:
        report.attempted += 1
        try:
            if _keeps_name(action, force):
                report.skipped += 1
                continue
            if action.kind == "rename" and action.new_name is not None:
                client.rename_function(action.va, action.new_name)
                report.renamed += 1
            if action.comment is None:
                continue
            # Every kind refreshes our plate comment, so it tracks the
            # Python source; a hand-written one needs --force (AZ-194).
            # Read it now: the plan's ``plate`` may be stale.
            if not force and plate_state(client.get_comment(action.va)) == "hand":
                report.comments_kept += 1
                continue
            client.set_comment(action.va, action.comment, kind="plate")
            report.commented += 1
        except GhidraClientError as exc:
            report.errors.append(
                f"0x{action.va:08X} ({action.kind}): {exc}")
    return report


