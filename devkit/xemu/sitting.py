# --- CLI -----------------------------------------------------------------------------------------------------------

def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("run", help="run a sitting spec (TOML): builds, then one sitting of its cases")
    p.add_argument("spec", type=Path)
    p.add_argument("--dry-run", action="store_true", help="check the spec offline; build and start nothing")
    p.add_argument("--redo", action="store_true", help="run every case again, not only those without a row")
    p = sub.add_parser("serve", help="take a slot and serve exec requests until --end, idle or a signal")
    p.add_argument("name", help="the sitting's name (sandbox group, evidence folder suffix)")
    p.add_argument("--ev", type=Path, help="its evidence folder (default xemu-oracle-<date>-<name> in $EV)")
    p.add_argument("--step", help="the step it serves, for the report")
    p.add_argument("--wait", type=float, default=WAIT_S, help=f"seconds to wait for a slot (default {WAIT_S:.0f})")
    p.add_argument("--idle", type=float, help=f"tear down after this long idle (default {IDLE_S:.0f}; never with "
                   "--owner-pad)")
    p.add_argument("--lease", type=float, default=LEASE_S,
                   help=f"seconds before it yields its sandbox to a waiting sitting, between requests (default "
                        f"{LEASE_S:.0f}; never with --owner-pad)")
    p.add_argument("--keep", action=argparse.BooleanOptionalAction,
                   help="keep W and the private folder (default: only with --owner-pad, for W's input-record.txt)")
    p.add_argument("--fresh", action="store_true", help="no shared warm boots and no held sandbox (Step X.81d): a "
                   "version-adoption sitting, which cold-boots on purpose")
    xo.add_box_args(p)
    xo.add_owner_pad_arg(p)
    p = sub.add_parser("exec", help="run a driver file (or stdin) in a serving sitting; print its output")
    p.add_argument("sock", type=Path, help="the socket serve printed (<private folder>/exec.sock)")
    p.add_argument("file", nargs="?", default="-", help="the driver (default stdin)")
    p.add_argument("--end", action="store_true", help="end the sitting (its teardown runs)")
    p = sub.add_parser("queue", help="run a queue file's drivers on N serving sittings at once (--add: append to it)")
    p.add_argument("file", type=Path, help="the queue: a driver a line (a path, or a name in <ev>/drivers), end stops")
    p.add_argument("sandboxes", nargs="*", help="the serving sittings' names (their sockets: <ev>/logs/sock-<name>.txt)")
    p.add_argument("--ev", type=Path, help="the evidence folder the serves share (its logs/ and drivers/)")
    p.add_argument("--add", nargs="+", metavar="LINE", help="append these lines under the queue's lock, then exit")
    p.add_argument("--timeout", type=float, default=3000.0, help="seconds a driver may run (default 3000)")
    p.add_argument("--until-empty", action="store_true", help="stop at an empty queue (default: wait for more)")
    sub.add_parser("selftest", help="offline checks (no xemu)")
    a = ap.parse_args(argv)
    sys.stdout.reconfigure(line_buffering=True)
    if a.cmd == "selftest":
        return selftest()
    if a.cmd == "run":
        return run_spec(a.spec, dry_run=a.dry_run, redo=a.redo)
    if a.cmd == "queue":
        if a.add:
            queue_add(a.file, a.add)
            return 0
        if not a.sandboxes or a.ev is None:
            ap.error("queue: the serving sittings' names and --ev (or --add)")
        socks = {n: Path((a.ev / "logs" / f"sock-{n}.txt").read_text(encoding="utf-8").strip()) for n in a.sandboxes}
        ran = queue(a.file, socks, logs=a.ev / "logs", drivers=a.ev / "drivers", timeout=a.timeout,
                    until_empty=a.until_empty)
        xo.log(json.dumps({n: len(v) for n, v in ran.items()}))
        return 0
    if a.cmd == "exec":
        src = END_REQUEST if a.end else (sys.stdin.read() if a.file == "-" else Path(a.file).read_text(encoding="utf-8"))
        sys.stdout.write(send(a.sock, src))
        return 0
    with Sitting(a.name, step=a.step, ev=a.ev, wait_s=a.wait, lease_s=a.lease, keep=a.keep,
                 headless=a.headless, deterministic=a.deterministic, app=a.app, record=a.record,
                 owner_pad=a.owner_pad, pad_port=a.pad_port, live_pads=a.live_pads, fresh=a.fresh) as sit:
        sock = sit.private / "exec.sock"

        def ready() -> None:   # the socket by name, for exec and queue (logs/sock-<name>.txt)
            (sit.ev / "logs" / f"sock-{sit.name}.txt").write_text(f"{sock}\n", encoding="utf-8")
            xo.log(json.dumps({"serving": str(sock), "W": str(sit.sb.w), "ev": str(sit.ev)}))
        serve(sit, sock, a.idle, between=sit.maybe_yield, ready=ready)
    return 0


if __name__ == "__main__":
    sys.exit(main())
