def seconds(v) -> float:
    """``90``, ``"90s"``, ``"45m"`` or ``"4h"`` in seconds."""
    if isinstance(v, (int, float)):
        return float(v)
    m = re.fullmatch(r"\s*(\d+(?:\.\d+)?)\s*([hms]?)\s*", str(v))
    if not m:
        raise ValueError(f"not a duration: {v!r} (90, 90s, 45m, 4h)")
    return float(m[1]) * {"h": 3600, "m": 60, "s": 1, "": 1}[m[2]]


