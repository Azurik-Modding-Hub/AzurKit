def check_spec(spec: dict, tags: list[str] | None = None) -> list[str]:
    """What's wrong with a spec, offline (``--dry-run``): unknown keys, a case with no start state or not one
    thing to do, an unknown build, tag, element, button, measure or file. ``tags``: the loadable tags (default the
    fixtures README's; with ``AZURIK_XEMU_HDD``, ``vanilla-rzp-*`` too)."""
    tags = xo.oracle_tags() if tags is None else tags
    private = bool(os.environ.get("AZURIK_XEMU_HDD"))
    bad = []

    def keys(where: str, d, allowed) -> None:
        if not isinstance(d, dict):
            bad.append(f"{where} is not a table")
        elif extra := sorted(set(d) - allowed):
            bad.append(f"{where}: unknown key(s) {extra}")

    def tag_ok(where: str, t) -> None:
        if not (isinstance(t, str) and (t in tags or (private and t.startswith(xo.PRIVATE_TAG)))):
            bad.append(f"{where}: {t!r} is not a loadable tag (the fixtures README's; vanilla-rzp-* on a private HDD)")
    keys("[sitting]", spec["sitting"], SITTING_KEYS)
    if not spec["sitting"].get("name"):
        bad.append("[sitting] has no name")
    if spec["sitting"].get("headless", xo.DEFAULT_HEADLESS) not in xo.HEADLESS:
        bad.append(f"[sitting] headless {spec['sitting']['headless']!r}: one of {', '.join(xo.HEADLESS)} "
                   "(1 offscreen, null no rendering, 0 a window)")
    if "app" in spec["sitting"] and not (xo.app_path(spec["sitting"]["app"]) / "Contents/MacOS/xemu").is_file():
        bad.append(f"[sitting] app {spec['sitting']['app']!r}: fork, kept or an xemu.app's path")
    for k in ("wait", "lease"):
        if k in spec["sitting"]:
            try:
                seconds(spec["sitting"][k])
            except ValueError as e:
                bad.append(f"[sitting] {k}: {e}")
    for name, b in spec["build"].items():
        keys(f"[build.{name}]", b, BUILD_KEYS)
        if name == "vanilla":
            bad.append("[build.vanilla]: 'vanilla' is the vanilla ISO itself")
        elif ("cli" in b) == bool(set(b) & {"enable", "params", "config_mod"}):
            bad.append(f"[build.{name}]: either cli (azurkit's argv) or packs (enable, params, config_mod)")
        elif "enable" in b:
            from azurkit.tools import mods
            if unknown := next((p for p in b["enable"] if p not in mods.PACKS), None):
                bad.append(f"[build.{name}]: no pack {unknown!r}")
    seen = set()
    for n, c in enumerate(spec["cases"]):
        where = f"case {c.get('id', n)!r}"
        keys(where, c, CASE_KEYS)
        if not c.get("id") or c.get("id") in seen:
            bad.append(f"{where}: needs an id of its own")
        seen.add(c.get("id"))
        st, do = c.get("start", {}), c.get("do", {})
        keys(f"{where} start", st, START_KEYS)
        keys(f"{where} do", do, DO_KEYS)
        if not isinstance(st, dict) or not isinstance(do, dict):
            continue
        if sum(k in do for k in DOS) != 1:
            bad.append(f"{where}: do needs exactly one of {', '.join(DOS)}")
        if not ({"boot", "loadvm"} & set(st)) and "py" not in do:
            bad.append(f"{where}: start needs boot or loadvm (each case starts from a known state, so it can rerun)")
        if "boot" in st and st["boot"] != "vanilla" and st["boot"] not in spec["build"]:
            bad.append(f"{where}: no build {st['boot']!r}")
        for k in ("tag", "loadvm", "place"):
            if k in st:
                tag_ok(f"{where} start.{k}", st[k])
        for e, v in st.get("kit", {}).items():
            if e not in recipes.ELEMENTS or v not in range(4):
                bad.append(f"{where}: kit {e} = {v!r} (elements {', '.join(recipes.ELEMENTS)}, levels 0-3)")
        for e, v in st.get("frags", {}).items():
            if e[0] not in recipes.FRAG_ELEMS or e not in (*recipes.ELEMENTS, "life", *recipes.FRAG_ELEMS) \
                    or v not in range(5):
                bad.append(f"{where}: frags {e} = {v!r} (earth, air, fire, water or life; 0-4)")
        if "hop" in st and not (isinstance(st["hop"], dict) and set(st["hop"]) == {"level", "spot"}):
            bad.append(f"{where}: hop = {{ level = \"levels/...\", spot = \"<playerLocation>\" }}")
        if "warp" in st and not (isinstance(st["warp"], dict) and "level" in st["warp"]
                                 and set(st["warp"]) <= {"level", "spot"}):
            bad.append(f"{where}: warp = {{ level = \"levels/...\" }} (and spot = \"<playerLocation>\" if not startspot)")
        for k, acts in do.get("schedule", {}).items():
            for a in acts if isinstance(acts, list) else [acts]:
                p = str(a).split()
                analog = len(p) == 3 and (p[0], p[1]) in {("axis", n) for n in ("lx", "ly", "rx", "ry")} \
                    | {("trigger", "lt"), ("trigger", "rt")} and re.fullmatch(r"-?\d+(\.\d+)?", p[2])
                if not (str(k).isdigit() and (p in (["clear"], ["stop"]) or analog or (
                        len(p) == 2 and p[0] in ("down", "up") and p[1] in xo.PAD))):
                    bad.append(f"{where}: schedule {k} = {a!r} (tick: 'down <button>', 'up <button>', "
                               f"'axis <lx|ly|rx|ry> <v>', 'trigger <lt|rt> <v>', 'clear', 'stop'; buttons "
                               f"{' '.join(xo.PAD)})")
        if "walk_to" in do and "level" not in do:
            bad.append(f"{where}: walk_to needs the level its router is for (level = \"e2\")")
        if "l3_replay" in do:
            seg = do["l3_replay"]
            try:
                l3.pads(seg if isinstance(seg, list) else json.loads((spec["dir"] / seg).read_text(encoding="utf-8")))
            except (OSError, ValueError, KeyError, TypeError) as e:
                bad.append(f"{where}: l3_replay: {e}")
        if "py" in do and not (spec["dir"] / do["py"]).is_file():
            bad.append(f"{where}: no driver {do['py']!r} beside the spec")
        for m in c.get("measure", []):
            if m not in (*MEASURES, "inventory"):
                bad.append(f"{where}: no measure {m!r} ({', '.join([*MEASURES, 'inventory'])})")
    return bad


def make_builds(builds: dict, out: Path, iso: Path) -> dict[str, dict]:
    """Each ``[build.<name>]`` from the vanilla ``iso`` into ``out`` (D27, D36): packs through MCP
    ``pack_build_iso``'s code (``sdk.build``), or ``cli``, azurkit's argv (``build ...``), given ``--iso`` and
    ``--out``. Any failure stops the sitting before its slot (D35)."""
    import hashlib

    read_file = xo.read_file
    res = {}
    for name, b in builds.items():
        dst = out / f"{name}.iso"
        if "cli" in b:
            argv = [str(Path(sys.executable).with_name("azurkit")), *map(str, b["cli"]), "--iso", str(iso),
                    "--out", str(dst)]
            r = subprocess.run(argv, capture_output=True, text=True)
            if r.returncode:
                raise SystemExit(f"build {name}: azurkit exit {r.returncode}: {r.stderr.strip()[-400:]}")
            what = "azurkit " + " ".join(map(str, b["cli"]))
        else:
            r = _pack_tool()(str(iso), str(dst), enable=b.get("enable"), params=b.get("params"),
                             config_mod=json.dumps(b["config_mod"]) if "config_mod" in b else None)
            if not r.get("success"):
                raise SystemExit(f"build {name}: {r.get('error')}")
            what = f"packs {b.get('enable')} {json.dumps(b.get('params', {}))}" + (" + a config mod" if "config_mod" in b else "")
        with dst.open("rb") as f:
            sha = hashlib.file_digest(f, "sha256").hexdigest()
        res[name] = {"path": dst, "iso_sha12": sha[:12], "what": what,
                     "xbe_sha12": hashlib.sha256(read_file(dst, "default.xbe")).hexdigest()[:12]}
        xo.log(f"build {name}: iso {sha[:12]}, xbe {res[name]['xbe_sha12']} ({what})")
    return res


