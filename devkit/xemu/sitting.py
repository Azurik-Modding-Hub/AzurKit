"""Dev-only sitting kit for the xemu oracle (Step X.9): one import, and a sitting is a few lines.

Every sitting of 2026-10-13 copied the same helpers into its evidence folder (an exec server 14 times, the R2/R6/R7
RAM recipes 15 times, a queue script, menu waits, a screenshot helper) and lost runs to bugs in the copies. They
live here, on the harness (``devkit/xemu/oracle.py``) and the RAM recipes
(``src/azurkit/tools/randomizer/live/recipes.py``)::

    from devkit.xemu import sitting as xs
    with xs.Sitting("roll", step="X.9") as s:          # a slot (queued), a private folder, guaranteed teardown
        s.loadvm("vanilla-exit")
        s.kit(air=0)                                    # R2: the exact kit (the elements it doesn't name: 0)
        cap = s.capture(60, {2: "down lstick_up", 20: "down black", 22: "up black"}, label="roll")
        s.result({"case": "roll", "states": sorted({r["state"] for r in cap["rows"]})})
    # teardown: down (the baselines), REPORT.txt's generated header, the private folder deleted

    uv run --locked python -m devkit xemu sitting run <spec.toml> [--dry-run] [--redo]  # a declarative sitting
    uv run --locked python -m devkit xemu sitting serve <name> [--ev DIR] [--wait S]   # the exec server
    uv run --locked python -m devkit xemu sitting exec <sock> FILE|-                   # a driver, run in it
    uv run --locked python -m devkit xemu sitting queue <file> <name>... --ev DIR       # drivers on N serves at once
    uv run --locked python -m devkit xemu sitting selftest                             # offline checks

A sitting's public results go to its evidence folder (``xemu-oracle-<date>-<name>/`` in ``$EV``: ``results/runs.jsonl``,
``captures/``, ``logs/session.log``, ``REPORT.txt``); positions stay in memory and in the private folder
(``/tmp/<name>-sit.*``, mode 700, deleted at teardown): a capture's public copy has every position relative to its
first row. Dev only (devkit, Step 4.14a3), never a player's verb; pytest runs only its offline ``selftest``
(``tests/test_xemu_harness.py``, marked ``xemu``), which launches no xemu (D11); the sandbox rules are the
``azurik-xemu-oracle`` skill's.
Nothing here prints game bytes: a string read from the guest is a known name or its sha256[:12] (``guest_str``). A
model-swap sitting's rows are ``devkit/xemu/sittings/model_kit.py``'s (Step X.45).
"""

