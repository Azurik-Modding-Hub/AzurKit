def cheat_code(name: str | int) -> tuple[int, list[set[str]]]:
    """A ``CHEATS`` code by name or index: its index and steps (sets of pipe pad inputs)."""
    hit = next(((k, v) for k, v in CHEATS.items() if name in (k, v[0])), None)
    if hit is None:
        raise ValueError(f"no cheat {name!r}: one of {', '.join(CHEATS)} (or 0-9)")
    return hit[1][0], [set(st.split("+")) for st in hit[1][1].split()]


def cheat_owner(b: bytes) -> dict:
    """The cheat owner's fields: the code's progress (steps matched) and index, the step timer, gem mode, the big
    head, the state (0 idle, 1 free camera, 2 menu, 3 pop a menu, 4 close them all) and the menus open."""
    i = lambda o: struct.unpack_from("<i", b, o)[0]  # noqa: E731
    return {"prog": i(0), "code": i(4), "timer": struct.unpack_from("<f", b, 8)[0], "gems": b[0xC], "big_head": b[0xD],
            "state": i(0x1C), "menus": (i(0x24) - i(0x20)) // 4, "camera": i(0x2C) != 0}


def menu_key(row: dict, level: str, last: str | None) -> str | None:
    """The warp's next tap in the debug menu at ``row`` (``Sitting.menu_row``): START opens "Change level...";
    its rows (sorted by label: the path's last part, '_' as ' '; movie scenes among the levels) are walked down or
    up to ``level``, where it selects; None once it turned back (no row for ``level``)."""
    if row["path"] is None:
        if row["label"] != "Change level...":
            return "dpad_up"
        return "start" if not row["open"] else None if last == "dpad_up" else "dpad_down"
    if row["path"] == level:
        return "select"
    key = "dpad_down" if row["label"] < level.rsplit("/", 1)[-1].replace("_", " ") else "dpad_up"
    return None if last in ("dpad_down", "dpad_up") and last != key else key


def _host(h: dict) -> str:
    """A boot's host-time counters in a line (``xo.host_delta``'s, Step X.58)."""
    return (f"translate {h.get('translate_s')} s ({h.get('translations')} blocks), apu {h.get('apu_s')} s, "
            f"idle {h.get('idle_s')} s skipped" + (" since the relaunch" if h.get("since") == "launch" else ""))


def _display(st: dict) -> str:
    """How the sandbox showed the game: headless offscreen or null (the build's own startup line), or a window
    (asked for, or a build without the headless mode); and whether it ran deterministic (Step X.22)."""
    det = (f"; deterministic ({' '.join(xo.ICOUNT_ARGS)})" if st.get("deterministic")
           else "; not deterministic (real time)") + ("; strict CPUID (XEMU_STRICT_CPUID=1)" if st.get("strict_cpuid")
                                                      else "") + (
        "; guest bugchecks reported (XEMU_GUEST_BUGCHECK=1)" if st.get("bugcheck") else "")
    if st.get("headless"):
        return f"headless {st['headless']}{det}"
    asked = st.get("headless_requested")
    return "a window" + (f" (asked headless {asked}: this build has no headless mode)" if asked not in (None, "0")
                         else "") + det


def _disc_sha12(st: dict) -> str | None:
    """The sandbox's disc's sha256[:12], from its baseline line (W still there) or its sandbox.json."""
    try:
        lines = (Path(st["W"]) / "baseline_before.txt").read_text(encoding="utf-8").splitlines()
        return next(ln for ln in lines if ln.endswith(f" {st['disc']}"))[:12]
    except (OSError, KeyError, StopIteration):
        return (st.get("disc_sha12") or {}).get("dvd.iso")


def _xemu_sha12(st: dict) -> str | None:
    """The sha256[:12] of the xemu binary the sandbox cloned and launched (its app's ``Contents/MacOS/xemu``), from
    its baseline line (W still there) or the copy ``Sitting.up`` kept (AZ-482: an upstream download's version alone
    doesn't tie the launch to the download whose digest was checked)."""
    try:
        lines = (Path(st["W"]) / "baseline_before.txt").read_text(encoding="utf-8").splitlines()
        return next(ln for ln in lines if ln.endswith(f" {st['app']}/Contents/MacOS/xemu"))[:12]
    except (OSError, KeyError, StopIteration):
        return st.get("xemu_sha12")


def _brief(row: dict) -> str:
    """A case row's key numbers for the report: its top-level numbers and booleans, a few."""
    skip = {"case", "attempt", "s", "time"}
    return ", ".join(f"{k} {v}" for k, v in row.items() if k not in skip and isinstance(v, (int, float, bool))
                     and not isinstance(v, str))[:240]


# --- measures: coordinate-free numbers from a capture's rows ----------------------------------------------------------

def _hs(r: dict) -> float:
    return math.hypot(r["vx"], r["vy"])


def m_jump(rows: list[dict]) -> dict:
    """The first jump (``jump_summary``): its takeoff tick, v0, airborne ticks, landing and apex over the takeoff."""
    j = xo.jump_summary(rows)
    return {f"jump_{k}": j.get(k) for k in ("takeoff_k", "v0", "airborne_ticks", "landed", "apex_bz")}


def m_roll(rows: list[dict]) -> dict:
    """The roll (state 0x100): its ticks, the speed into it and its most, and the body centre's distance over it
    (from the tick before it to its last; a capture's ``c`` field)."""
    rl = [i for i, r in enumerate(rows) if r["state"] == 0x100]
    if not rl:
        return {"roll_ticks": 0}
    a, b = max(rl[0] - 1, 0), rl[-1]
    out = {"roll_ticks": len(rl), "roll_hspeed_entry": round(_hs(rows[a]), 4),
           "roll_hspeed_max": round(max(_hs(rows[i]) for i in rl), 4)}
    if "c" in rows[a]:
        out["roll_m"] = round(math.hypot(rows[b]["c"][0] - rows[a]["c"][0], rows[b]["c"][1] - rows[a]["c"][1]), 4)
    return out


def m_hspeed(rows: list[dict]) -> dict:
    return {"hspeed_max": round(max(map(_hs, rows)), 4), "hspeed_last": round(_hs(rows[-1]), 4)} if rows else {}


def m_states(rows: list[dict]) -> dict:
    s = [r["state"] for r in rows]
    return {"states": sorted({hex(v) for v in s}), "state_changes": sum(a != b for a, b in zip(s, s[1:]))}


def m_hp(rows: list[dict]) -> dict:
    hp = [r["hp"] for r in rows if isinstance(r.get("hp"), int)]
    return {"hp_first": hp[0], "hp_last": hp[-1], "hp_min": min(hp)} if hp else {}


MEASURES = {"jump": m_jump, "roll": m_roll, "hspeed": m_hspeed, "states": m_states, "hp": m_hp}


def judge(expect: dict | None, row: dict) -> str:
    """A case's outcome: ``done`` with no expectations, else ``pass`` or ``fail: <what>``; an expectation is a
    value (equal) or ``[lo, hi]`` (a number in that range)."""
    if not expect:
        return "done"
    bad = []
    for k, want in expect.items():
        got = row.get(k)
        rng = isinstance(want, list) and len(want) == 2 and all(isinstance(w, (int, float)) for w in want)
        ok = (isinstance(got, (int, float)) and not isinstance(got, bool) and want[0] <= got <= want[1]) if rng \
            else got == want
        if not ok:
            bad.append(f"{k} {got!r}, want {want!r}")
    return "pass" if not bad else "fail: " + "; ".join(bad)


