    def kit(self, **levels: int) -> dict:
        """R2, the exact kit (D114): these element levels and every other element 0; returns them read back."""
        if bad := set(levels) - set(recipes.ELEMENTS):
            raise ValueError(f"no element {sorted(bad)[0]!r}: one of {', '.join(recipes.ELEMENTS)}")
        self.apply(recipes.element_levels(self.sb.read_u32, {e: levels.get(e, 0) for e in recipes.ELEMENTS},
                                          self._va))
        return {e: v for e, v in self.inventory().items() if e.startswith("level.")}

    def frags(self, element: str, n: int) -> dict:
        """R2: fragments 1..``n`` of ``element`` (earth, air, fire, water, life, or its letter) held, the rest not."""
        e = element[0]
        self.apply(recipes.fragments(self.sb.read_u32, e, n, self._va))
        inv = self.inventory()
        return {k: inv[f"fg{e}{k}"] for k in range(1, 5)}

    def keys(self, held: dict[str, int]) -> dict:
        """R2: the key slots hold exactly ``held`` ({key fourcc: count}); returns them read back by tag."""
        self.apply(recipes.keys(self.sb.read_u32, held, self._va))
        inv = recipes.chain(self.sb.read_u32, self._va)["inv"]
        slots = [self.sb.read(inv + recipes.KEY0 + 12 * i, 8) for i in range(5)]
        return {b[:4].rstrip(b"\0").decode("ascii", "replace"): int.from_bytes(b[4:], "little", signed=True)
                for b in slots if b[:4] != b"\0\0\0\0"}

    def set_hp(self, hp: int) -> int:
        """The player's HP (critter+0x210), at the player tick the guest is halted at (else the next)."""
        if self.sb.g.regs()["eip"] != xo.PLAYER_TICK and self.tick() is None:
            raise SystemExit("no player tick to set the HP at")
        ent = self.sb.g.u32(self.sb.g.regs()["esp"] + 4)
        return self.sb.write_i32(self.sb.read_u32(ent + 0x20) + recipes.CR_HP, hp)

    @staticmethod
    def hold_hp(hp: int):
        """A ``capture`` on_tick: the HP back to ``hp`` whenever it fell below (a fight's enemies, AZ-305)."""
        def hold(sb, row, rows):
            at = sb.read_u32(row["ent"] + 0x20) + recipes.CR_HP
            if sb.read_i32(at) < hp:
                sb.write_i32(at, hp)
        return hold

    def record_spot(self, tag: str, disc: str | None = None) -> dict:
        """``loadvm`` ``tag`` (with ``disc``, as ``Sandbox.loadvm``: an owner demo names it for a tag it didn't
        save) and keep its player's spot (body centre, facing, cell, level) in memory, for ``place(spot=tag)``
        after a boot; returns the level and cell only."""
        if "entity" not in (res := self.loadvm(tag, disc=disc)):
            raise SystemExit(f"{tag}: {res.get('first_tick')}")
        ent = int(res["entity"], 16)
        crit = self.sb.read_u32(ent + 0x20)
        self.spots[tag] = {"centre": struct.unpack("<3f", self.sb.read(crit + recipes.CR_BODY, 12)),
                           "quat": struct.unpack("<4f", self.sb.read(crit + recipes.CR_QUAT, 16)),
                           "cell": recipes.cell_of(self.sb.read_u32, crit, self.chain()), "level": self.level()}
        return {"spot": tag, "level": self.spots[tag]["level"], "cell": self.spots[tag]["cell"]}

    def place(self, feet=None, yaw_deg: float | None = None, *, spot: str | None = None, cell: int | None = None,
              settle: int = 15, tol_m: float = PLACE_TOL_M) -> dict:
        """R6, a teleport the game's own way: to ``feet`` facing ``yaw_deg`` (game angle; forward is
        (-sin, cos)), or onto a ``record_spot`` spot (its cell and facing), at rest (AZ-437: the place stops the
        player's velocity, so a body warped onto a1's rising tree lift no longer flies 6.8 m up); then ``settle``
        player ticks. Returns whether it settled (the ticks ran and the body centre ended within ``tol_m`` of the
        target: AZ-409) and the distance (no positions)."""
        if self.sb.g.regs()["eip"] != xo.PLAYER_TICK and self.tick() is None:
            raise SystemExit("no player tick to place the player at")
        quat = None
        if spot is not None:
            s = self.spots[spot]
            if (here := self.level()) != s["level"]:
                raise SystemExit(f"spot {spot} is in {s['level']}, the player in {here}")
            feet, quat, cell = (s["centre"][0], s["centre"][1], s["centre"][2] - recipes.LIFT + 0.1), s["quat"], s["cell"]
        self.apply(recipes.place(self.sb.read_u32, feet, math.radians(yaw_deg or 0.0), quat=quat, cell=cell,
                                 entity=self.sb.g.u32(self.sb.g.regs()["esp"] + 4), va=self._va))
        ok = all(self.tick(6.0) is not None for _ in range(settle))
        ent = self.sb.g.u32(self.sb.g.regs()["esp"] + 4)
        centre = struct.unpack("<3f", self.sb.read(self.sb.read_u32(ent + 0x20) + recipes.CR_BODY, 12))
        off = math.dist(centre, (feet[0], feet[1], feet[2] + recipes.LIFT))
        return {"placed": spot or "a point", "settled": ok and off <= tol_m, "off_m": round(off, 3)}

    def hop(self, level: str, spot: str, *, budget: float = 90.0, settle: int = 20) -> dict:
        """R7, a level hop (``levels/fire/f6``, a playerLocation's name): post the request, then run until
        ``settle`` player ticks on the ground or in water in the new level, pressing A on a stall (a dialog)."""
        if self.sb.g.regs()["eip"] != xo.PLAYER_TICK and self.tick() is None:
            raise SystemExit("no player tick to post the level request at")
        self.apply(recipes.hop(self.sb.read_u32, level, spot, va=self._va))
        return self._arrive(time.monotonic(), budget, settle)

    def _arrive(self, t0: float, budget: float, settle: int) -> dict:
        """After a level request: run until ``settle`` player ticks on the ground or in water in the new level,
        pressing A on a stall (a dialog); beside an owner demo ``budget`` times ``BACKGROUND_SCALE`` (D526)."""
        budget *= self.sb._slow()
        loads, n, last_a = [], 0, 0.0
        while time.monotonic() - t0 < budget:
            eip = self.sb.wait_bp([xo.PLAYER_TICK, xo.LOAD_LEVEL], 2.5)
            if eip is None:
                if time.monotonic() - last_a > 2.5:
                    self.sb.press("a", seconds=0.3)
                    last_a = time.monotonic()
                continue
            if eip == xo.LOAD_LEVEL:
                loads.append(xo.level_path(self.sb.g))
                n = 0
            elif loads and self.sb.entity_row(self.sb.g.u32(self.sb.g.regs()["esp"] + 4))["state"] in (0, 3, 6):
                n += 1
                if n >= settle:
                    return {"ok": True, "level": self.level(), "loads": loads, "s": round(time.monotonic() - t0, 1)}
        return {"ok": False, "level": self.level(), "loads": loads, "s": round(time.monotonic() - t0, 1)}

    def clear_dialog(self, tries: int = 4) -> bool:
        """A dialog or cutscene stops the player tick: press A (real input) until it runs; halted there."""
        for _ in range(tries):
            if self.tick(3.0) is not None:
                return True
            self.sb.press("a", seconds=0.3)
        return self.tick(3.0) is not None

    # -- the game's own cheat codes and debug menu (Step X.17) --
    def _hold(self, want: set[str], held: set[str]) -> set[str]:
        """The pipe pad holds the inputs ``want`` (pad names), from ``held``: ups, then downs."""
        for k in sorted(held - want):
            self.sb.send(f"up {self.sb.code(k)}")
        for k in sorted(want - held):
            self.sb.send(f"down {self.sb.code(k)}")
        return set(want)

    def cheat_tick(self, timeout: float = 5.0) -> dict:
        """Run to the cheat handler's next call (once per game update while no popup or load holds the game;
        halted there): its owner (EDI) and the owner's fields (``cheat_owner``); beside an owner demo ``timeout``
        times ``BACKGROUND_SCALE`` (D526, as ``tick``'s)."""
        timeout *= self.sb._slow()
        if self.sb.wait_bp([self._va(CHEAT_TICK)], timeout) is None:
            raise SystemExit(f"no cheat tick within {timeout:.0f} s: a popup, cutscene or load holds the game")
        owner = self.sb.g.regs()["edi"]
        return {"owner": owner, **cheat_owner(self.sb.read(owner, 0x30))}

    def cheat(self, name: str | int, *, tries: int = 3) -> dict:
        """Enter a cheat code (``CHEATS``, by name or index) with real pad input through the pipe, frame by frame at
        the cheat tick: each update the pad holds the next step not yet matched, so a step the last one already
        satisfies counts at once; the first step goes when the idle 1 s timer has most of its second left. Halted
        at the code's action (0x16610) once it ran; returns the code, its frames and tries."""
        idx, steps = cheat_code(name)
        run = self._va(CHEAT_RUN)
        for t in range(1, tries + 1):
            self.sb.send("clear")   # nothing held: a stuck input would fail every step
            held, started, frames, last = set(), 0, 0, 0
            while frames < 300:
                o = self.cheat_tick()
                frames += 1
                if o["state"] or o["gems"]:
                    raise SystemExit(f"cheat {name}: the cheat owner is in state {o['state']}"
                                     f"{' (gem mode: WHITE ends it)' if o['gems'] else ''}; codes match only when idle")
                if not started:
                    if o["prog"] == 0 and o["timer"] < 0.3:
                        held, started = self._hold(steps[0], held), frames
                    continue
                if (o["prog"] and o["code"] != idx) or (last and not o["prog"]) \
                        or (not o["prog"] and frames - started > 30):
                    break   # another code's first step, its 1 s ran out, or the first step never matched
                last = o["prog"]
                if o["prog"] >= len(steps):
                    self._hold(set(), held)
                    if self.sb.wait_bp([run], 3.0 * self.sb._slow()) == run \
                            and self.sb.read_u32(self.sb.g.regs()["esp"] + 8) == idx:
                        return {"cheat": name, "code": idx, "frames": frames, "tries": t}
                    break
                held = self._hold(steps[o["prog"]], held)
            self._hold(set(), held)
            for _ in range(40):   # its step timer runs out
                self.cheat_tick()
        raise SystemExit(f"cheat {name}: not entered in {tries} tries")

    def menu_row(self, owner: int) -> dict:
        """The debug menu's current row (the top menu's +0x8C points 8 bytes into it): its label, whether a
        submenu row is open, and a "Change level..." row's path (the row action 0x12A50's argument)."""
        ctx = self.sb.read_u32(self.sb.read_u32(owner + 0x24) - 4)
        row = self.sb.read_u32(ctx + 0x8C) - 8
        b = self.sb.read(row, 0x90)
        label = b[0x1C:0x80].split(b"\0")[0].decode("latin-1")
        act, arg = struct.unpack_from("<II", b, 0x84)
        path = self.sb.read(arg, 0x50).split(b"\0")[0].decode("latin-1") if act == self._va(LEVEL_ROW) else None
        return {"label": label, "open": bool(b[0x8C]), "path": path}

    def _tap(self, key: str, frames: int = 4) -> dict:
        """One press of ``key`` held ``frames`` cheat ticks, then as many released; the last tick's owner state."""
        held = self._hold({key}, set())
        for _ in range(frames):
            self.cheat_tick()
        self._hold(set(), held)
        for _ in range(frames):
            o = self.cheat_tick()
        return o

    def warp(self, level: str, spot: str | None = None, *, budget: float = 90.0, settle: int = 20) -> dict:
        """The native debug menu's level warp: the menu code, START on "Change level...", the level's row
        (``levels/water/w1``; every level index.xbr lists but training_room and selector), START. Its row posts
        the request a levelSwitch posts (no movie, the level, spot "startspot"), then ``hop``'s steady ticks in
        the new level. All real pad input; a ``spot`` other than startspot is written into the request's spot
        slot as the row posts it (one RAM write: placed). Returns the arrival (``hop``'s), the code's frames, the
        taps, the request as posted and whether the spot was written."""
        t0 = time.monotonic()
        code = self.cheat("menu")
        for _ in range(10):
            if (o := self.cheat_tick())["state"] == 2:
                break
        else:
            raise SystemExit(f"warp: the menu never opened (cheat owner state {o['state']})")
        taps, key = [], None
        while key != "select":
            row = self.menu_row(o["owner"])
            key = menu_key(row, level, taps[-1] if taps else None)
            if key == "select":
                break
            if key is None or len(taps) > 80:
                raise SystemExit(f"warp: no row for {level} in the menu (at {row['label']!r})")
            taps.append(key)
            o = self._tap(key)
            for _ in range(20):   # a row moves, or opens, a few updates after its release
                if self.menu_row(o["owner"]) != row:
                    break
                o = self.cheat_tick()
        row_va, ret = self._va(LEVEL_ROW), None
        held = self._hold({"start"}, set())   # START's edge runs the row two updates later, held or not
        for n in range(30):
            if self.sb.wait_bp([self._va(CHEAT_TICK), row_va], 5.0 * self.sb._slow()) == row_va:
                ret = self.sb.read_u32(self.sb.g.regs()["esp"])
                break
            if n == 4:
                held = self._hold(set(), held)
        self._hold(set(), held)
        if ret is None or self.sb.wait_bp([ret], 3.0 * self.sb._slow()) != ret:
            raise SystemExit(f"warp: START on {level}'s row ran no level action")
        buf = self.sb.read_u32(self.chain()["req"] + recipes.R_LEVEL)
        posted = [self.sb.read(buf + k * recipes.STR_SLOT, 0x50).split(b"\0")[0].decode("latin-1") for k in range(3)]
        written = bool(spot) and spot != posted[2]
        if written:
            self.apply([(buf + 2 * recipes.STR_SLOT, spot.encode("ascii") + b"\0")])
        res = self._arrive(time.monotonic(), budget, settle)
        return {**res, "s": round(time.monotonic() - t0, 1), "code_frames": code["frames"], "taps": len(taps) + 1,
                "posted": dict(zip(("movie", "level", "spot"), posted)), "spot_written": written}

    # -- measuring --
    def capture(self, n_ticks: int, schedule=None, *, label: str, body: bool = True, hold_hp: int | None = None,
                origin: dict | None = None, **kw) -> dict:
        """``Sandbox.capture`` (tick-locked), its raw JSON in the private folder and a public copy
        (``scrub``: positions relative to ``origin``, by default its first row) in ``captures/<label>.json``.
        ``body`` adds the body centre (cx, cy, cz); ``hold_hp`` holds the HP at that value. Returns the raw
        capture (positions: keep them in memory)."""
        fields = {**(body_fields() if body else {}), **kw.pop("fields", {})}
        if hold_hp is not None:
            kw["on_tick"] = both(kw.get("on_tick"), self.hold_hp(hold_hp))
        cap = self.sb.capture(n_ticks, schedule, fields=fields, label=label, **kw)
        if held := lost_tick(stop := cap["meta"]["stop"]) and not self.demo:   # AZ-484: what held it, named
            # a watched guest that bugchecked: xemu's report names it (held), no census run in the halted kernel
            bugchecked = self.watching and self._bugchecked()
            cap["meta"]["held_by"] = dict(BUGCHECK_CENSUS) if bugchecked else self.census()
        if label is not None:   # an unlabelled capture has no public copy (AZ-484: captures/None.json overwritten)
            pub = scrub(cap, origin)
            (self.ev / "captures" / f"{label}.json").write_text(json.dumps(pub, indent=0), encoding="utf-8")
        if held and self.watching:   # the row ends here, its capture kept
            self.held(label or "a capture", stop, cap["meta"]["held_by"])
        return cap

    def l3_replay(self, segments: list[dict], *, label: str | None = None, scene: bool = False) -> dict:
        """An L3 snapshot here (into the private store; deleted at teardown unless ``keep``), the input string
        run in L3 from it, then replayed in xemu from the same start: the comparison (no positions)."""
        label = label or f"{self.name}-{time.strftime('%H%M%S')}"
        snap = self.sb.snapshot(label, scene=scene)
        self.snapshots.append(Path(snap["path"]))
        return xo.l3_replay(self.sb, label, segments, scene=scene)

    def screenshot(self, name: str) -> Path:
        """The guest's frame as a PNG in the evidence folder's ``screens/`` (``Sandbox.screenshot``: QMP
        ``screendump``, offscreen or windowed; refused under the null renderer, the deterministic default: a
        sitting that needs pictures asks for ``headless="1"``, and ``deterministic=True`` for pictures that
        reproduce, taken paused; ``null_ram=True`` on v0.16.1 keeps the null renderer's RAM and draws only the
        pictures asked for; a picture whose frame predates the last load or restore is advanced to a fresh one or
        refused, ``picture-stale``, Step X.61)."""
        return self.sb.screenshot(name, self.ev / "screens" / f"{name}.png")

    def result(self, row: dict) -> dict:
        """One results row (``results/runs.jsonl``; coordinate-free values only), tagged with its sandbox (this
        sitting's name: several serves may share one evidence folder, ``queue``), appended under the file's lock."""
        row = {"time": stamp(), "sandbox": self.name, **row}
        self.rows.append(row)
        import fcntl   # POSIX's own (tests/test_contracts.py)
        with (self.ev / "results" / "runs.jsonl").open("a", encoding="utf-8") as f:
            fcntl.flock(f, fcntl.LOCK_EX)
            f.write(json.dumps(row, default=str) + "\n")
        xo.log(json.dumps(row, default=str)[:600])
        return row

