def _done(ev: Path) -> set[tuple[str, int]]:
    """The (case, attempt) pairs ``results/cases.jsonl`` already holds without an error."""
    p = ev / "results" / "cases.jsonl"
    if not p.exists():
        return set()
    rows = [json.loads(ln) for ln in p.read_text(encoding="utf-8").splitlines() if ln.strip()]
    return {(r["case"], r["attempt"]) for r in rows if not str(r.get("outcome", "")).startswith("error")}


def run_case(sit: Sitting, case: dict, i: int, builds: dict, routers: dict, spec_dir: Path) -> dict:
    """One attempt of a case: its start, its one thing to do, its measures and expectations; one row in
    ``results/cases.jsonl``. An error costs the row, not the sitting; an xemu that died is relaunched on its W
    (keeping its slot) and the case run again from its start, ``retries`` times (default 1)."""
    row: dict = {"case": case["id"], "attempt": i, "labels": []}
    t0 = time.monotonic()
    tries = 1 + case.get("retries", 1)
    for n in range(1, tries + 1):
        try:
            row["labels"] = []
            row.update(_case(sit, case, i, builds, routers, spec_dir, row["labels"]))
            break
        except Teardown:
            raise
        except (Exception, SystemExit) as e:  # noqa: BLE001  (one case's failure is its row)
            if (td := sit.after_signal(e)) is not None:
                raise td from e
            gone = sit.sb is not None and not sit.sb.alive()
            if gone and n < tries:   # a crash (a lost GPU device's exit among them)
                cause = xo.exit_cause(sit.sb.w)
                row.setdefault("incidents", []).append(f"try {n}: xemu died ({cause}; {type(e).__name__}: "
                                                       f"{str(e)[:120]}); relaunched on its W, case run again")
                sit.log(f"case {case['id']}#{i}: xemu died ({cause}); relaunching")
                sit.sb.relaunch()
                continue
            row.update(outcome=f"error: {type(e).__name__}: {str(e)[:200]}", error=traceback.format_exc()[-800:])
            with contextlib.suppress(Exception):
                sit.sb.g.cmd("?")   # a case that died at a breakpoint leaves it armed
            break
    if sit.signalled is not None:   # a Teardown a callback swallowed and the case ran on: no row, no next case
        raise Teardown(f"signal {sit.signalled}: tearing down (case {case['id']}#{i} ran on past it: its Teardown "
                       "was swallowed inside a callback; no row kept)")
    row["s"] = round(time.monotonic() - t0, 1)
    row.setdefault("outcome", judge(case.get("expect"), row))
    sit.cases.append(row)
    with (sit.ev / "results" / "cases.jsonl").open("a", encoding="utf-8") as f:
        f.write(json.dumps({"time": stamp(), **row}, default=str) + "\n")
    sit.log(f"case {case['id']}#{i}: {row['outcome']} in {row['s']} s ({', '.join(row['labels'])})")
    return row


def _case(sit: Sitting, case: dict, i: int, builds: dict, routers: dict, spec_dir: Path, labels: list) -> dict:
    st, do, out = case.get("start", {}), case["do"], {}

    def label(what: str) -> None:
        if what not in labels:
            labels.append(what)
    if "boot" in st:
        b = sit.boot(builds[st["boot"]]["path"], st.get("tag", "vanilla-ig-w1"), warm=st.get("warm", True))
        out["boot"] = {k: b.get(k) for k in ("build", "level", "s", "tries", "warm", "host_profile") if k in b}
        label("booted")
    if "loadvm" in st:
        sit.loadvm(st["loadvm"])
        label("placed")
    if "kit" in st:
        out["kit"] = sit.kit(**st["kit"])
        label("placed")
    if "frags" in st:
        out["frags"] = {e: sit.frags(e, n) for e, n in st["frags"].items()}
        label("placed")
    if "hop" in st:
        h = sit.hop(st["hop"]["level"], st["hop"]["spot"])
        out["hop"] = {k: h[k] for k in ("ok", "level", "s")}
        if not h["ok"]:
            raise SystemExit(f"the hop to {st['hop']} never settled (in {h['level']})")
        label("placed")
    if "warp" in st:
        w = sit.warp(st["warp"]["level"], st["warp"].get("spot"))
        out["warp"] = {k: w[k] for k in ("ok", "level", "s", "spot_written")}
        if not w["ok"]:
            raise SystemExit(f"the warp to {st['warp']} never settled (in {w['level']})")
        label("placed" if w["spot_written"] else "warped")
    if "place" in st:
        out["place"] = sit.place(spot=st["place"])
        label("placed")
    if "hp" in st:
        sit.set_hp(st["hp"])
        label("placed")
    measures = case.get("measure", [])
    inv0 = sit.inventory() if "inventory" in measures else None
    lab = f"{case['id']}-{i}"
    if "capture" in do:
        sched = {int(k): v for k, v in do.get("schedule", {}).items()}
        cap = sit.capture(do["capture"], sched, label=lab, hold_hp=do.get("hold_hp"),
                          bps=[int(str(v), 0) for v in do.get("bps", [])])
        label("real input" if sched else "watched")
        rows = cap["rows"]
        out.update(ticks=len(rows), complete=cap["meta"]["complete"], stop=cap["meta"]["stop"])
        for m in measures:
            if m != "inventory":
                out.update(MEASURES[m](rows))
    elif "walk_to" in do:
        from devkit.xemu import route as xr
        res = xr.walk_to(sit.sb, routers[(do["level"], do.get("prof", "logic"))], do["walk_to"],
                         tier=do.get("tier", "hard"), air=do.get("air", 0), ticks=do.get("ticks", 1800), label=lab)
        out.update({k: res.get(k) for k in ("reached", "why", "left_m", "end_zone", "replans", "dialogs")})
        label("real input")
    elif "l3_replay" in do:
        seg = do["l3_replay"]
        seg = seg if isinstance(seg, list) else json.loads((spec_dir / seg).read_text(encoding="utf-8"))
        out.update(sit.l3_replay(seg, label=f"{sit.name}-{lab}-{time.strftime('%H%M%S')}", scene=do.get("scene", False)))
        label("l3 replay")
    else:
        path = spec_dir / do["py"]
        ns = {**sit.namespace(), "case": case, "attempt": i, "out": out}
        exec(compile(path.read_text(encoding="utf-8"), str(path), "exec"), ns)
        label("driver")
    if inv0 is not None:
        inv1 = sit.inventory()
        out["inventory_moved"] = {k: [inv0[k], v] for k, v in inv1.items() if inv0.get(k) != v}
    return out


def run_spec(path: Path | str, *, dry_run: bool = False, redo: bool = False) -> int:
    """Run a spec: check it offline, make its builds and routers before the slot, then in one sitting record the
    spots its cases place onto and run each case attempt not already in ``results/cases.jsonl`` (``redo``: all).
    Exit 0 when every case passed or had no expectations, 1 when one failed or errored, 2 for a bad spec."""
    spec = load_spec(Path(path))
    if problems := check_spec(spec):
        for p in problems:
            xo.log(f"spec: {p}")
        return 2
    cfg, cases = spec["sitting"], spec["cases"]
    xo.log(f"spec {Path(path).name}: sitting {cfg['name']}, {len(spec['build'])} build(s), "
           f"{sum(c.get('repeat', 1) for c in cases)} case attempt(s)")
    if dry_run:
        xo.log("dry run: the spec resolves (builds' packs, tags, buttons, measures, files); nothing built or started")
        return 0
    iso = xo.vanilla_iso()
    scratch = Path(tempfile.mkdtemp(prefix=f"{slug(cfg['name'])}-builds.", dir="/tmp"))
    try:
        builds = {"vanilla": {"path": iso, "what": "the vanilla ISO"}} | make_builds(spec["build"], scratch, iso)
        routers = {}
        for c in cases:
            if "walk_to" in c["do"] and (key := (c["do"]["level"], c["do"].get("prof", "logic"))) not in routers:
                from devkit.xemu import route as xr
                t0 = time.monotonic()
                routers[key] = xr.router(iso, *key)
                xo.log(f"router {key}: {time.monotonic() - t0:.0f} s")
        sit = Sitting(cfg["name"], step=cfg.get("step"), ev=cfg.get("ev"), wait_s=seconds(cfg.get("wait", WAIT_S)),
                      lease_s=seconds(cfg.get("lease", LEASE_S)), keep=cfg.get("keep", False),
                      headless=cfg.get("headless"), deterministic=cfg.get("deterministic"), app=cfg.get("app"),
                      fresh=cfg.get("fresh", False))
        sit.builds = {n: {k: v for k, v in b.items() if k != "path"} for n, b in builds.items() if n != "vanilla"}
        done = set() if redo else _done(sit.ev)
        with sit:
            for tag in sorted({c["start"]["place"] for c in cases if "place" in c.get("start", {})}):
                sit.record_spot(tag)
            for c in cases:
                for i in range(c.get("repeat", 1)):
                    if (c["id"], i) in done:
                        sit.log(f"case {c['id']}#{i}: in results/cases.jsonl already (--redo runs it again)")
                        continue
                    sit.maybe_yield()
                    run_case(sit, c, i, builds, routers, spec["dir"])
        return 0 if all(c["outcome"] in ("done", "pass") for c in sit.cases) else 1
    finally:
        shutil.rmtree(scratch, ignore_errors=True)   # its own mktemp folder (D147)


# --- the exec server: one process keeps the sandbox (and reach models) across short driver calls ----------------

END_REQUEST = "#!end"


def serve(sit: Sitting, sock: Path, idle_s: float | None = None, between=None, ready=None) -> None:
    """Serve ``exec`` requests on the Unix socket ``sock`` (0600, in the private folder): each is Python source,
    run in one shared namespace (``Sitting.namespace``: ``s``, ``sb``, ``xo``, ``xr``, ``result``, ...), holding W's
    QMP turn (``xo.qmp_turn``: a demo's recorder and replug watcher step aside until it ends, AZ-644); its
    output, or its traceback, goes back. ``#!end`` (``exec --end``) or ``idle_s`` with no request (default
    ``IDLE_S``; never for an owner demo) ends it. ``between()`` runs after each request; ``ready()`` once it listens."""
    if idle_s is None:
        idle_s = math.inf if sit.demo else IDLE_S
    ns = sit.namespace()
    sock.unlink(missing_ok=True)
    srv = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    srv.bind(str(sock))
    sock.chmod(0o600)
    srv.listen(1)
    srv.settimeout(5.0)
    if ready is not None:
        ready()
    last = time.monotonic()
    try:
        while time.monotonic() - last < idle_s:
            try:
                c, _ = srv.accept()
            except socket.timeout:
                continue
            with c:
                c.settimeout(None)
                src = b"".join(iter(lambda: c.recv(65536), b"")).decode()
                if src.strip() == END_REQUEST:
                    c.sendall(b"ending: tearing down\n")
                    return
                ns["sb"] = sit.sb
                out = io.StringIO()
                turn = xo.qmp_turn(sit.sb.w) if sit.sb is not None else contextlib.nullcontext()
                try:   # W's QMP turn for the whole request (AZ-644): a demo's watchers step aside meanwhile
                    with turn, contextlib.redirect_stdout(out), contextlib.redirect_stderr(out):
                        exec(compile(src, "<driver>", "exec"), ns)
                except SystemExit as e:
                    out.write(f"SystemExit: {e}\n")
                except BaseException:  # noqa: BLE001  (a driver's error is its output, not the server's end)
                    out.write(traceback.format_exc())
                if sit.signalled is not None:   # the request ran into a signal (a Teardown a callback swallowed)
                    out.write(f"ended by signal {sit.signalled}: any error above came after it (AZ-396); tearing "
                              "down\n")
                with contextlib.suppress(OSError):
                    c.sendall(out.getvalue().encode())
                if sit.signalled is not None:
                    sit.log(f"exec server: signal {sit.signalled} during a request: tearing down")
                    return
            last = time.monotonic()
            if sit.sb is not None:   # its QMP connection goes between requests (Step X.32b): another process may drive
                sit.sb._close_qmp()
            if between is not None:
                between()
        sit.log(f"exec server idle {idle_s:.0f} s: tearing down")
    finally:
        srv.close()
        sock.unlink(missing_ok=True)


def send(sock: Path, src: str, timeout: float | None = None) -> str:
    """Send one request to ``serve``; returns its output."""
    s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    s.settimeout(timeout)
    s.connect(str(sock))
    with s:
        s.sendall(src.encode())
        s.shutdown(socket.SHUT_WR)
        return b"".join(iter(lambda: s.recv(65536), b"")).decode()


# --- the queue: one file of drivers that N serving sittings pull from (Step X.45) -----------------------------------

def _queue_lock(qfile: Path):
    """The queue file's lock (``<file>.lock``, flock: closing it lets go)."""
    import fcntl   # POSIX's own (tests/test_contracts.py)
    f = qfile.with_name(qfile.name + ".lock").open("a+", encoding="utf-8")
    fcntl.flock(f, fcntl.LOCK_EX)
    return f


def queue_add(qfile: Path, lines: list[str]) -> None:
    """Append ``lines`` to the queue under its lock (not ``>>``: a take rewrites the file, which loses an append); an
    ``end`` already there goes (it would stop every line added after it: end the added lines with their own)."""
    with _queue_lock(qfile):
        old = [ln.strip() for ln in qfile.read_text(encoding="utf-8").splitlines()] if qfile.exists() else []
        tmp = qfile.with_name(qfile.name + ".tmp")
        tmp.write_text("".join(f"{ln}\n" for ln in [*(ln for ln in old if ln and ln != "end"), *lines]),
                       encoding="utf-8")
        tmp.replace(qfile)


def _queue_take(qfile: Path, back: str | None = None) -> str | None:
    """Under the queue's lock: its first line taken out (``end`` stays there, for every runner), or ``back`` put at its
    head (None then); None when it's empty."""
    with _queue_lock(qfile):
        lines = [ln.strip() for ln in qfile.read_text(encoding="utf-8").splitlines()] if qfile.exists() else []
        lines, line = [ln for ln in lines if ln], None
        if back is not None:
            lines.insert(0, back)
        elif not lines or lines[0] == "end":
            return lines[0] if lines else None
        else:
            line = lines.pop(0)
        tmp = qfile.with_name(qfile.name + ".tmp")
        tmp.write_text("".join(f"{ln}\n" for ln in lines), encoding="utf-8")
        tmp.replace(qfile)
        return line


def queue(qfile: Path, socks: dict[str, Path], *, logs: Path, drivers: Path | None = None, timeout: float = 3000.0,
          poll_s: float = 5.0, until_empty: bool = False) -> dict[str, list[str]]:
    """Run the queue file's drivers (a line each: a driver's path or a name in ``drivers``; ``end`` stops) on N serving
    sittings at once, ``socks`` {sandbox name: its exec socket}: one worker per sandbox takes the next line under the
    file's lock (qrun.sh's head/tail/mv lost or doubled rows with two runners) and runs it there. Serves that share
    one evidence folder write one ``results/runs.jsonl``, each row tagged with its sandbox (``Sitting.result``); a
    driver's output goes to ``logs/<driver>.<sandbox>.txt``, the queue's lines to ``logs/queue.log``. A serve that is
    gone puts its line back and stops its worker. With ``until_empty`` a worker stops at an empty queue, else it waits
    for more. Returns the lines each sandbox ran."""
    import threading
    logs.mkdir(parents=True, exist_ok=True)
    ran: dict[str, list[str]] = {n: [] for n in socks}

    def note(what: str) -> None:
        import fcntl   # POSIX's own (tests/test_contracts.py)
        with (logs / "queue.log").open("a", encoding="utf-8") as f:
            fcntl.flock(f, fcntl.LOCK_EX)
            f.write(f"=== {what} {time.strftime('%H:%M:%S')}\n")

    def work(name: str, sock: Path) -> None:
        while (line := _queue_take(qfile)) != "end":
            if line is None:
                if until_empty:
                    return
                time.sleep(poll_s)
                continue
            path = Path(line).expanduser()
            if not path.is_file() and drivers is not None:
                path = drivers / f"{line}.py"
            if not path.is_file():
                note(f"{line}: no such driver, skipped ({name})")
                continue
            note(f"{line} on {name}")
            t0 = time.monotonic()
            try:
                out = send(sock, path.read_text(encoding="utf-8"), timeout)
            except (FileNotFoundError, ConnectionRefusedError) as e:
                _queue_take(qfile, back=line)
                note(f"{name}'s serve is gone ({type(e).__name__}): {line} back at the head; {name} stops")
                return
            except OSError as e:   # a timeout: it may still run there, and the next request waits its turn
                out = f"queue: {type(e).__name__}: {e}\n"
            (logs / f"{path.stem}.{name}.txt").write_text(out, encoding="utf-8")
            ran[name].append(line)
            note(f"done {line} on {name} in {time.monotonic() - t0:.0f} s")
    workers = [threading.Thread(target=work, args=item, daemon=True) for item in socks.items()]
    for w in workers:
        w.start()
    for w in workers:
        w.join()
    return ran


